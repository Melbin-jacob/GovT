#!/usr/bin/env python3
"""Write docs/fr-ui-strings.md: every French string Claude Code wrote, with its status.

Sources (same keys as their English files, checked by tests):
- services/control-centre/src/control_centre/locales/fr.toml   (web UI strings)
- services/rulebook/src/rulebook/locales/explanations.fr.toml   (generated explanations:
  impact-report reasons, maintenance items, ServiceNow task text)

    python3 scripts/fr_strings.py [--check] [docs/fr-ui-strings.md]
"""

from __future__ import annotations

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UI = ROOT / "services/control-centre/src/control_centre/locales"
RULEBOOK = ROOT / "services/rulebook/src/rulebook/locales"
ENGINE = ROOT / "services/assessment-engine/src/assessment_engine/locales"
RULES = ROOT / "data/rules"
DEFAULT = ROOT / "docs/fr-ui-strings.md"
PROVIDED = "Provided by the project owner"
UNVERIFIED = "Unverified, written by Claude Code"


def _load(path: Path) -> dict:  # type: ignore[type-arg]
    return tomllib.loads(path.read_text("utf-8"))


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _table(fr: dict[str, str], en: dict[str, str], owner: set[str]) -> list[str]:
    lines = ["| Key | French | English | Status |", "|---|---|---|---|"]
    for key in sorted(fr):
        status = PROVIDED if key in owner else UNVERIFIED
        lines.append(f"| `{key}` | {_cell(fr[key])} | {_cell(en.get(key, ''))} | {status} |")
    return lines


def markdown() -> str:
    ui_fr, ui_en = _load(UI / "fr.toml"), _load(UI / "en.toml")
    owner = set(ui_fr.get("provenance", {}).get("provided_by_project_owner", []))
    ui = (ui_fr["strings"], ui_en["strings"])
    ex = (
        _load(RULEBOOK / "explanations.fr.toml")["templates"],
        _load(RULEBOOK / "explanations.en.toml")["templates"],
    )
    ae = (
        _load(ENGINE / "messages.fr.toml")["messages"],
        _load(ENGINE / "messages.en.toml")["messages"],
    )
    rule_fr: dict[str, str] = {}
    rule_en: dict[str, str] = {}
    for path in sorted(RULES.glob("*.rules.toml")):
        data = _load(path)
        catalog = data["meta"]["catalog"]
        for name, fact in data.get("facts", {}).items():
            rule_fr[f"{catalog} fact {name}"] = fact["fr"]
            rule_en[f"{catalog} fact {name}"] = fact["en"]
        for rule in data.get("rule", []):
            rule_fr[f"{catalog} rule {rule['control']}"] = rule["fr"]
            rule_en[f"{catalog} rule {rule['control']}"] = rule["en"]
    total = len(ui[0]) + len(ex[0]) + len(ae[0]) + len(rule_fr)
    lines = [
        "# French strings (web UI, generated explanations, assessment engine, rules)",
        "",
        "Generated by `python3 scripts/fr_strings.py`; CI fails if it is stale.",
        "",
        "Every French string is **unverified, written by Claude Code**, unless marked",
        "**provided by the project owner**. Policy wording never comes from these files: it",
        "comes from the French catalog. Have a qualified translator review the unverified",
        "strings before any use outside the demo.",
        "",
        f"{total} strings: {len(owner)} provided by the project owner, "
        f"{total - len(owner)} unverified.",
        "",
        "## Web UI (`services/control-centre/src/control_centre/locales/fr.toml`)",
        "",
        *_table(ui[0], ui[1], owner),
        "",
        "## Generated explanations (`services/rulebook/src/rulebook/locales/explanations.fr.toml`)",
        "",
        "Impact-report reasons, maintenance items, excluded systems, due-date bases and the",
        "French half of ServiceNow task text. `{name}` marks a value filled in at run time.",
        "",
        *_table(ex[0], ex[1], set()),
        "",
        "## Assessment-engine messages (`services/assessment-engine/src/assessment_engine/"
        "locales/messages.fr.toml`)",
        "",
        *_table(ae[0], ae[1], set()),
        "",
        "## Rule interpretations and fact labels (`data/rules/*.rules.toml`)",
        "",
        "The rules themselves are unverified drafts (approved as drafts); annotators confirm",
        "them alongside the golden set.",
        "",
        *_table(rule_fr, rule_en, set()),
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    paths = [a for a in argv if not a.startswith("--")]
    target = Path(paths[0]) if paths else DEFAULT
    text = markdown()
    if check:
        if not target.is_file() or target.read_text("utf-8") != text:
            print(f"{target} is stale: run `python3 scripts/fr_strings.py`")
            return 1
        print(f"{target} is current")
        return 0
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))

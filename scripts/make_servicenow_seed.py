"""Generate data/demo/servicenow/seed.json for the mock ServiceNow (stdlib only).

FICTIONAL demo records derived from data/inventory/systems.csv, plus SYS-009, a record with
missing fields that demonstrates data-gap handling. Deterministic: run it again after
changing systems.csv (a test checks the committed seed is current).
"""

import csv
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIFECYCLE = {
    "production": "Installed",
    "pilot": "In Maintenance",
    "development": "On Order",
    "retired": "Retired",
}
IMPACT = {"I": "1", "II": "2", "III": "3", "IV": "4"}


def sys_id(*parts: str) -> str:
    return hashlib.sha256("/".join(parts).encode()).hexdigest()[:32]


def build() -> dict:
    rows = list(csv.DictReader((ROOT / "data/inventory/systems.csv").open(encoding="utf-8")))
    tenants = sorted({r["Tenant"] for r in rows})
    departments = sorted({r["Department"] for r in rows})
    groups = [
        {"sys_id": sys_id("group", t), "name": t, "description": f"FICTIONAL tenant {t}"}
        for t in tenants
    ]
    depts = [{"sys_id": sys_id("dept", d), "name": d} for d in departments]
    users = [
        {
            "sys_id": sys_id("user", r["Owner email"]),
            "user_name": r["Owner email"].split("@")[0],
            "name": r["Owner"],
            "email": r["Owner email"],
        }
        for r in rows
    ]
    apps = [
        {
            "sys_id": sys_id("ci", r["System ID"]),
            "name": r["Name"],
            "correlation_id": r["System ID"],
            "owned_by": sys_id("user", r["Owner email"]),
            "managed_by_group": sys_id("group", r["Tenant"]),
            "department": sys_id("dept", r["Department"]),
            "install_status": LIFECYCLE[r["Lifecycle"]],
            "u_aia_impact_level": IMPACT[r["AIA impact level"]],
            "u_govhub_profiles": r["Profiles"],
            "short_description": r["Notes"],
        }
        for r in rows
    ]
    apps.append(
        {  # deliberately incomplete: no impact level, no owner, no profiles
            "sys_id": sys_id("ci", "SYS-009"),
            "name": "Unregistered Chat Assistant Pilot (fictional)",
            "correlation_id": "SYS-009",
            "owned_by": "",
            "managed_by_group": sys_id("group", "dept-example-services"),
            "department": sys_id("dept", "Department of Example Services (fictional)"),
            "install_status": "In Maintenance",
            "u_aia_impact_level": "",
            "u_govhub_profiles": "",
            "short_description": "FICTIONAL demo record with missing fields (data-gap demo)",
        }
    )
    return {
        "_comment": "FICTIONAL mock ServiceNow data for tests, CI and the demo. Generated by "
        "scripts/make_servicenow_seed.py from data/inventory/systems.csv.",
        "accounts": {
            "govhub.integration": {
                "password": "mock-only-password",
                "roles": ["u_govhub_task_writer", "cmdb_read"],
            },
            "readonly.tester": {"password": "mock-only-password", "roles": ["cmdb_read"]},
        },
        # Mimics the ACLs in docs/servicenow-setup.md. Tables not listed: readable by any
        # authenticated account (sys_user, sys_user_group, cmn_department), not writable.
        "acls": {
            "cmdb_ci_business_app": {"read": ["cmdb_read"], "write": []},
            "u_govhub_task": {"read": ["u_govhub_task_writer"], "write": ["u_govhub_task_writer"]},
        },
        "display_fields": {
            "sys_user": "name",
            "sys_user_group": "name",
            "cmn_department": "name",
            "cmdb_ci_business_app": "name",
            "u_govhub_task": "number",
        },
        "references": {
            "cmdb_ci_business_app": {
                "owned_by": "sys_user",
                "managed_by_group": "sys_user_group",
                "department": "cmn_department",
            },
            "u_govhub_task": {
                "assigned_to": "sys_user",
                "assignment_group": "sys_user_group",
                "cmdb_ci": "cmdb_ci_business_app",
            },
        },
        "journal_fields": ["work_notes"],
        "tables": {
            "sys_user": users,
            "sys_user_group": groups,
            "cmn_department": depts,
            "cmdb_ci_business_app": apps,
            "u_govhub_task": [],
        },
    }


if __name__ == "__main__":
    out = ROOT / "data/demo/servicenow/seed.json"
    text = json.dumps(build(), indent=2, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        sys.exit(0 if out.read_text(encoding="utf-8") == text else 1)
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}")
